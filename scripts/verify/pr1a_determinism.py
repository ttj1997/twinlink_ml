"""PR1a -- determinism of the data generation and agreement with the records.

For master seeds 1 and 2 (and the fixed holdout seed 999) every data set is generated three
times: twice in this process and once in a fresh interpreter. Each array is hashed (SHA-256 of
the raw bytes), and each split block (train / val / test in split order) gets a hash of all its
runs' content. Then:

* run IDs, split digests, excitation fingerprints and seed bundles are compared with the
  records (``arch_learning_curve_projected.jsonl``, ``arch_learning_curve_constant_trained
  .jsonl``);
* the process config is compared numerically (PyYAML, everything except ``provenance``)
  between the pre-cut archive at the record commit and the current YAML;
* the ``src/twinlink_ml`` sources at every record commit are compared with the current tree
  on the AST level (docstrings/comments stripped), so that "regenerated today" is shown to mean
  "generated by the same code".

    python scripts/verify/pr1a_determinism.py            # full audit, writes the artifact
    python scripts/verify/pr1a_determinism.py --emit excited 1   # helper: print hashes as JSON
"""

from __future__ import annotations

import argparse
import ast
import json
import subprocess
import sys
from pathlib import Path
from typing import Any

import numpy as np
import yaml
from _common import (
    ARCHIVE_ROOT,
    CONFIG_PATH,
    REPO_ROOT,
    git,
    provenance,
    read_jsonl,
    require_clean_tree,
    write_artifact,
)
from _data import (
    HOLDOUT_SEED,
    digest_arrays,
    make_data,
    run_index,
    trajectory_arrays,
)

MASTER_SEEDS = (1, 2)
RECORD_COMMITS = {  # from PR0: commit -> which artifact it produced
    "0b3eaafc4f94efce9e8ec2550c6ca4ec5b37bf15": "arch_learning_curve_projected (GRU/LSTM/baselines)",
    "256d64414e": "arch_learning_curve_projected_extended (Transformer/xLSTM/Mamba)",
    "1b85ce4cda": "arch_learning_curve_constant_trained",
    "7e3fb1d878": "arch_epoch_budget_probe600",
}
DATA_PATH_MODULES = ("simulation/", "data/", "utils/seeding.py", "evaluation/experiments.py")


def hashes_of(kind: str, seed: int) -> dict[str, Any]:
    """Array hashes and per-split content hashes of one generated data set."""
    import hashlib

    data = make_data(kind, seed)
    arrays = trajectory_arrays(data)
    out: dict[str, Any] = {"arrays": digest_arrays(arrays)}
    per_split = {}
    for name, ids in (
        ("train", data.split.train),
        ("val", data.split.val),
        ("test", data.split.test),
    ):
        rows = run_index(data, ids)
        h = hashlib.sha256()
        for key in ("actions_realised", "disturbances", "states", "outputs", "measurements"):
            h.update(np.ascontiguousarray(arrays[key][rows]).tobytes())
        per_split[name] = {
            "n_runs": len(ids),
            "sha256": h.hexdigest(),
            "first_id": ids[0],
            "last_id": ids[-1],
        }
    out["splits"] = per_split
    out["split_digest"] = data.split.digest
    out["excitation_fingerprint"] = data.schedule.metadata["fingerprint"]
    out["process_fingerprint"] = data.process_config.fingerprint
    out["seeds"] = data.seeds.as_parameters()
    out["run_ids_train"] = list(data.split.train)
    out["run_ids_val"] = list(data.split.val)
    out["run_ids_test"] = list(data.split.test)
    out["all_run_ids"] = list(data.trajectory.run_id)
    return out


def fresh_process_hashes(kind: str, seed: int) -> dict[str, Any]:
    result = subprocess.run(
        [sys.executable, str(Path(__file__)), "--emit", kind, str(seed)],
        capture_output=True,
        text=True,
        check=True,
    )
    return json.loads(result.stdout.strip().splitlines()[-1])


def _strip_docstrings(tree: ast.AST) -> ast.AST:
    for node in ast.walk(tree):
        if isinstance(node, ast.Module | ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef):
            body = node.body
            if (
                body
                and isinstance(body[0], ast.Expr)
                and isinstance(body[0].value, ast.Constant)
                and isinstance(body[0].value.value, str)
            ):
                node.body = body[1:] or [ast.Pass()]
    return tree


def _ast_dump(source: str) -> str:
    return ast.dump(_strip_docstrings(ast.parse(source)), include_attributes=False)


def code_identity(commit: str) -> dict[str, Any]:
    """Compare ``src/twinlink_ml`` at ``commit`` (archive) with the working tree, AST level."""
    listing = git("ls-tree", "-r", "--name-only", commit, "--", "src/twinlink_ml", cwd=ARCHIVE_ROOT)
    old_files = {p for p in listing.splitlines() if p.endswith(".py")}
    new_files = {
        p.relative_to(REPO_ROOT).as_posix()
        for p in (REPO_ROOT / "src" / "twinlink_ml").rglob("*.py")
    }
    differing, only_old, only_new = [], sorted(old_files - new_files), sorted(new_files - old_files)
    for path in sorted(old_files & new_files):
        old_source = git("show", f"{commit}:{path}", cwd=ARCHIVE_ROOT)
        new_source = (REPO_ROOT / path).read_text(encoding="utf-8")
        if _ast_dump(old_source) != _ast_dump(new_source):
            differing.append(path)
    on_data_path = [p for p in differing if any(m in p for m in DATA_PATH_MODULES)]
    return {
        "commit": commit,
        "produced": RECORD_COMMITS.get(commit, "?"),
        "n_files_compared": len(old_files & new_files),
        "files_with_semantic_difference": differing,
        "differences_on_data_generation_path": on_data_path,
        "only_in_archive_commit": only_old,
        "only_in_current_tree": only_new,
    }


def config_equivalence(commit: str) -> dict[str, Any]:
    """Numeric config comparison, everything except the documentary ``provenance`` block."""
    old = yaml.safe_load(
        git("show", f"{commit}:conf/process/greybox_gab_placeholder.yaml", cwd=ARCHIVE_ROOT)
    )
    new = yaml.safe_load(CONFIG_PATH.read_text(encoding="utf-8"))

    def strip(d: dict[str, Any]) -> dict[str, Any]:
        return {k: v for k, v in d.items() if k != "provenance"}

    differing = sorted(
        k for k in set(strip(old)) | set(strip(new)) if strip(old).get(k) != strip(new).get(k)
    )
    return {
        "commit": commit,
        "numerically_identical_except_provenance": not differing,
        "differing_sections": differing,
        "provenance_keys_old": sorted(old.get("provenance", {})),
        "provenance_keys_new": sorted(new.get("provenance", {})),
    }


def main() -> None:
    require_clean_tree()
    report: dict[str, Any] = {"_provenance": provenance()}
    determinism: dict[str, Any] = {}
    generated: dict[tuple[str, int], dict[str, Any]] = {}

    jobs = [(kind, seed) for seed in MASTER_SEEDS for kind in ("excited", "constant_train")]
    jobs.append(("holdout", HOLDOUT_SEED))
    for kind, seed in jobs:
        first = hashes_of(kind, seed)
        second = hashes_of(kind, seed)
        third = fresh_process_hashes(kind, seed)
        generated[(kind, seed)] = first

        def same(a: dict[str, Any], b: dict[str, Any]) -> bool:
            return (
                a["arrays"] == b["arrays"]
                and a["splits"] == b["splits"]
                and a["all_run_ids"] == b["all_run_ids"]
            )

        determinism[f"{kind}_seed{seed}"] = {
            "n_arrays_hashed": len(first["arrays"]),
            "in_process_identical": same(first, second),
            "fresh_process_identical": same(first, third),
            "split_hashes": {k: v["sha256"][:16] for k, v in first["splits"].items()},
            "array_hashes_actions_states": {
                k: first["arrays"][k][:16] for k in ("actions_realised", "states", "measurements")
            },
        }
        print(
            kind,
            seed,
            determinism[f"{kind}_seed{seed}"]["in_process_identical"],
            determinism[f"{kind}_seed{seed}"]["fresh_process_identical"],
            flush=True,
        )
    report["determinism"] = determinism

    # --- run IDs / digests vs records ---------------------------------------------------
    rec_excited = read_jsonl("arch_learning_curve_projected")
    rec_constant = read_jsonl("arch_learning_curve_constant_trained")
    ids_check: dict[str, Any] = {}
    for seed in MASTER_SEEDS:
        for label, records, kind in (
            ("excited", rec_excited, "excited"),
            ("constant_train", rec_constant, "constant_train"),
        ):
            g = generated[(kind, seed)]
            rows = [r for r in records if r["params"]["master_seed"] == seed]
            fields = {
                "split/digest": {r["params"]["split/digest"] for r in rows},
                "excitation/fingerprint": {r["params"]["excitation/fingerprint"] for r in rows},
                "seed/data": {r["params"]["seed/data"] for r in rows},
                "seed/noise": {r["params"]["seed/noise"] for r in rows},
                "seed/model": {r["params"]["seed/model"] for r in rows},
            }
            regenerated = {
                "split/digest": g["split_digest"],
                "excitation/fingerprint": g["excitation_fingerprint"],
                "seed/data": g["seeds"]["seed/data"],
                "seed/noise": g["seeds"]["seed/noise"],
                "seed/model": g["seeds"]["seed/model"],
            }
            ids = g["all_run_ids"]
            id_pattern_ok = all(
                rid == f"mixed-{g['excitation_fingerprint']}-{i:05d}" for i, rid in enumerate(ids)
            )
            ids_check[f"{label}_seed{seed}"] = {
                "n_records": len(rows),
                "each_field_single_valued_in_records": all(len(v) == 1 for v in fields.values()),
                "regenerated_equals_record": {k: fields[k] == {regenerated[k]} for k in fields},
                "run_id_pattern_mixed_<fingerprint>_<index>": id_pattern_ok,
                "run_ids_unique": len(set(ids)) == len(ids),
                "n_runs": len(ids),
                "record_process_fingerprint": sorted(
                    {r["params"]["process/fingerprint"] for r in rows}
                ),
                "regenerated_process_fingerprint": g["process_fingerprint"],
            }
    report["ids_vs_records"] = ids_check
    report["note_ids"] = (
        "Run IDs are not stored in the records; the split digest (a hash over the ordered ID "
        "tuples) and the excitation fingerprint (embedded in every ID) are. Equality of these "
        "two is equality of all IDs."
    )

    # --- configuration and code identity across the repository cut --------------------
    report["config_equivalence"] = [config_equivalence(c) for c in RECORD_COMMITS]
    report["code_identity_across_cut"] = [code_identity(c) for c in RECORD_COMMITS]
    write_artifact("verify_pr1a_determinism", report)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--emit", nargs=2, metavar=("KIND", "SEED"))
    args = parser.parse_args()
    if args.emit:
        print(json.dumps(hashes_of(args.emit[0], int(args.emit[1]))))
    else:
        main()
