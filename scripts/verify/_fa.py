"""Shared helpers for the FA series (follow-up to the second addendum of Befund 65).

Network predictions of the ten archive LSTMs (moisture channel, n_train=64) on an arbitrary run set
stored like the EV3 data set (``dataset.npz``), cached under ``artifacts/runs/raw_fa/`` (git-ignored,
regenerated by the scripts). Imports no project evaluation code; windows and scalers come from the audit's
own ``pr3_metrics`` helpers, the networks are read from the archive checkpoints (nothing is trained).
"""

from __future__ import annotations

import numpy as np
from _common import ARCHIVE_ROOT, RUNS_DIR
from _data import make_data
from pr3_metrics import make_windows, net_predict, train_scaler

ARMS = ("excited", "constant")
SEEDS = (1, 2, 3, 4, 5)
MOIST = 1
CKPT = ARCHIVE_ROOT / "artifacts" / "checkpoints"
PREFIX = {"excited": "lstm", "constant": "constant_trained_lstm"}
KIND = {"excited": "excited", "constant": "constant_train"}
RAW_FA = RUNS_DIR / "raw_fa"


def load_dataset(path_name: str) -> object:
    """Run set in the layout of ``ev3_build_dataset.py`` (``raw_ev3/dataset.npz`` and analogues)."""
    from types import SimpleNamespace

    z = np.load(RUNS_DIR / path_name)
    traj = SimpleNamespace(
        run_id=tuple(str(r) for r in z["run_id"]),
        measurements=z["measurements"],
        outputs=z["outputs"],
        actions=z["actions"],
        disturbances=z["disturbances"],
        requested_actions=None,
    )
    return SimpleNamespace(trajectory=traj, scenario=z["scenario"], replicate=z["replicate"])


def flatten(w: dict) -> dict[str, np.ndarray]:
    """Window dict -> point arrays (window x 36 steps)."""
    return {
        "truth": w["truth"][..., MOIST].reshape(-1),
        "measured": w["ref"][..., MOIST].reshape(-1),
        "run": np.repeat(w["run"], 36),
        "start": np.repeat(w["start"], 36),
        "step": np.tile(np.arange(1, 37), len(w["run"])),
    }


def predictions(arm: str, name: str, data: object, ids: tuple[str, ...]) -> np.ndarray:
    """(5, points) moisture predictions of the arm's five networks on the run set ``ids``."""
    RAW_FA.mkdir(exist_ok=True)
    cache = RAW_FA / f"pred_{arm}_{name}.npy"
    if cache.exists():
        return np.load(cache)
    out = []
    for seed in SEEDS:
        pool = make_data(KIND[arm], seed)
        w = make_windows(data, ids, train_scaler(pool, 64))
        pred, _ = net_predict(CKPT / f"{PREFIX[arm]}_seed{seed}_n64.pt", w)
        out.append(pred[..., MOIST].reshape(-1))
    arr = np.stack(out)
    np.save(cache, arr)
    return arr


def points(data: object, ids: tuple[str, ...]) -> dict[str, np.ndarray]:
    """Truth/measured/run/start/step for the windows of ``ids`` (scaler-independent)."""
    pool = make_data("excited", 1)
    return flatten(make_windows(data, ids, train_scaler(pool, 64)))


def per_run_rmse(err: np.ndarray, run: np.ndarray) -> np.ndarray:
    return np.array([np.sqrt(np.mean(err[run == r] ** 2)) for r in np.unique(run)])
