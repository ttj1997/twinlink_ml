"""JSON Schemas of the module interface, as files for the consortium partners.

One function collects them, so that the export script (``scripts/export_api_schemas.py``) and the
test that keeps ``docs/api/`` up to date use the same source. The schemas are generated by
pydantic from the models in :mod:`twinlink_ml.api.schemas` and :mod:`twinlink_ml.api.bundle`; a
new pydantic version can change their wording, which the test then reports.
"""

from __future__ import annotations

import json
from typing import Any

from .base import SCHEMA_VERSION, Service
from .bundle import BundleManifest

__all__ = ["JSON_SCHEMA_DIALECT", "collect_schemas", "render_schema", "service_classes"]

JSON_SCHEMA_DIALECT = "https://json-schema.org/draft/2020-12/schema"


def service_classes() -> tuple[type[Service[Any, Any]], ...]:
    """The services of this package, in the order of the documentation."""
    from .forecast import ForecastService
    from .setpoint import SetpointService

    return (ForecastService, SetpointService)


def collect_schemas() -> dict[str, dict[str, Any]]:
    """File name to JSON Schema: three per service and one for the bundle manifest."""
    schemas: dict[str, dict[str, Any]] = {}
    for service in service_classes():
        for part, schema in service.json_schemas().items():
            schemas[f"{service.name}.{part}.schema.json"] = schema
    schemas["model_bundle_manifest.schema.json"] = BundleManifest.model_json_schema()
    return {
        name: {"$schema": JSON_SCHEMA_DIALECT, "x-schema-version": SCHEMA_VERSION, **schema}
        for name, schema in schemas.items()
    }


def render_schema(schema: dict[str, Any]) -> str:
    """The text of a schema file: sorted keys, two spaces, one trailing newline."""
    return json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=True) + "\n"
