r"""Residual data of the hybrid model and open-loop replays of the grey-box model.

The truth pool of one draw is generated by the Befund 94 pipeline (arm N) with the truth config.
:func:`replay` simulates the SAME runs -- realised actions, disturbances, physical initial
states of the excitation design -- with another config (the nominal prior knowledge, or the
refitted M2), open loop from the run start. :func:`residual_data` replaces the outputs of the
truth pool by ``truth - replay`` (noise-free outputs) and the measurements by
``measured truth - replay``; schedule, split, spec and seeds stay, so ``build_datasets`` forms
exactly the windows and run-level splits of the truth pool (Befund 94) on the residual.

Error identity used by the study: for the hybrid ``nominal + r_hat`` the prediction error is
``r_hat - (truth - nominal)``, i.e. the error of the residual network on the residual data; for
an open-loop grey-box model (M0, M2) it is ``-(truth - replay)``, the error of the zero predictor
on its residual data.
"""

from __future__ import annotations

import dataclasses
import warnings

import numpy as np

from twinlink_ml.evaluation.experiments import GeneratedData
from twinlink_ml.simulation import (
    GreyBoxFluidBedGranulator,
    PlaceholderConfigWarning,
    ProcessConfig,
)
from twinlink_ml.simulation.base import Trajectory

__all__ = ["replay", "residual_data", "run_rows"]


def run_rows(data: GeneratedData, run_ids: tuple[str, ...] | list[str]) -> list[int]:
    """Row index of every run id in the trajectory batch."""
    return [data.trajectory.run_id.index(r) for r in run_ids]


def replay(data: GeneratedData, config: ProcessConfig, rows: list[int] | None = None) -> Trajectory:
    """Open-loop simulation of the runs ``rows`` (all if ``None``) of ``data`` with ``config``.

    ``config`` gets the sample time of the pool (as ``generate_data`` does). Initial states from the
    physical columns of the excitation design, mapped with the replaying simulator.
    """
    rows = list(range(data.trajectory.n_runs)) if rows is None else list(rows)
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", PlaceholderConfigWarning)
        config = dataclasses.replace(
            config,
            numerics=dataclasses.replace(
                config.numerics, sample_time_s=data.process_config.numerics.sample_time_s
            ),
        )
        simulator = GreyBoxFluidBedGranulator(config)
    initial = None
    columns = data.schedule.initial_states
    if columns is not None:
        c = columns[rows]
        initial = simulator.state_from_physical(c[:, 0], c[:, 1], c[:, 2], c[:, 3])
    return simulator.rollout(
        data.trajectory.actions[rows],
        data.trajectory.disturbances[rows],
        run_id=tuple(data.trajectory.run_id[i] for i in rows),
        seed=data.seeds.noise_seed,
        initial_state=initial,
    )


def residual_data(data: GeneratedData, replayed: Trajectory) -> GeneratedData:
    """``data`` with outputs ``truth - replay`` and measurements ``measured - replay``."""
    truth = data.trajectory
    if replayed.run_id != truth.run_id:
        raise ValueError("the replay must cover every run of the pool in the same order")
    if replayed.metadata["output_names"] != truth.metadata["output_names"]:
        raise ValueError("output channels differ")
    residual = dataclasses.replace(
        truth,
        outputs=np.asarray(truth.outputs - replayed.outputs, dtype=np.float64),
        measurements=np.asarray(truth.measurements - replayed.outputs, dtype=np.float64),
        metadata={**truth.metadata, "residual_of": "truth - replay"},
    )
    return dataclasses.replace(data, trajectory=residual)
